/** 말풍선 속성. 버튼·칸에 펼쳐 넣는다. */
export function tip(label: string, hint?: string, title?: string) {
  const t = TIPS[label];
  const d = hint ?? t?.d;
  if (!d) return {};
  return { "data-tip": d, "data-tip-title": title ?? t?.t ?? label, ...(t?.k ? { "data-tip-key": t.k } : {}) };
}
